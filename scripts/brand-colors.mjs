// Writes shared/brand-colors.ts: the official colour of every Simple Icons logo the site uses,
// so tool and technology icons can show their own colours (in light mode, and on hover in dark mode).
// Usage: npm i --no-save simple-icons && node scripts/brand-colors.mjs
// Run it again after adding a `simple-icons:` icon anywhere in app/ or content/.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

let icons;

try {
  icons = await import('simple-icons');
}
catch {
  console.error('Missing "simple-icons". Install it without saving: npm i --no-save simple-icons');
  process.exit(1);
}

const repo = join(import.meta.dirname, '..');
const files = dir => readdirSync(dir).flatMap((entry) => {
  const path = join(dir, entry);

  return statSync(path).isDirectory() ? files(path) : /\.(vue|ts|ya?ml|md)$/.test(entry) ? [path] : [];
});

const used = new Set([...files(join(repo, 'app')), ...files(join(repo, 'content'))]
  .flatMap(file => [...readFileSync(file, 'utf8').matchAll(/simple-icons:([a-z0-9-]+)/g)].map(match => match[1])));

// Logos Simple Icons has since removed, with their official colours.
const removed = { amazonwebservices: 'FF9900', visualstudiocode: '007ACC' };
const bySlug = new Map([...Object.entries(removed), ...Object.values(icons).filter(icon => icon?.slug).map(icon => [icon.slug, icon.hex])]);
const colors = [...used].sort().map(slug => [slug, bySlug.get(slug)]).filter(([, hex]) => hex);
const missing = [...used].filter(slug => !bySlug.has(slug));

writeFileSync(join(repo, 'shared/brand-colors.ts'), `// Generated by scripts/brand-colors.mjs from Simple Icons; don't edit by hand.
/** The official colour of each \`simple-icons:\` logo the site uses, by icon name. */
export const brandColors: Record<string, string> = {
${colors.map(([slug, hex]) => `  ${/^[a-z_][a-z0-9_]*$/.test(slug) ? slug : `'${slug}'`}: '#${hex}'`).join(',\n')}
};
`);

console.log(`${colors.length} colours written${missing.length ? `; not in Simple Icons: ${missing.join(', ')}` : ''}`);
